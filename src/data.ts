/**
 * Generate a color for a new person at the given index.
 * Uses the ae hue array + HSL formulas from the spec.
 */
export function getColorForIndex(index: number): { color: string; lightColor: string; borderColor: string } {
  const N = ae[index % ae.length];
  const P = 28 + (index % 5) * 4;
  const H = 42 + (index % 4) * 4;
  return {
    color: `hsl(${N},${P}%,${H}%)`,
    lightColor: `hsl(${N},${P - 8}%,92%)`,
    borderColor: `hsl(${N},${P - 12}%,72%)`,
  };
}

